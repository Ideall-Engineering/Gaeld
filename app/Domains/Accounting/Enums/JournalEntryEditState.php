<?php

namespace App\Domains\Accounting\Enums;

use App\Domains\Accounting\Services\JournalEntryEditStateService;

/**
 * Why a posted journal entry may or may not be changed in place.
 *
 * Derived on demand by {@see JournalEntryEditStateService}, never stored.
 */
enum JournalEntryEditState: string
{
    /** Posted, in an open period, and owned by nobody else: amendable. */
    case Open = 'open';

    /** Not posted yet: the regular draft rules apply. */
    case Draft = 'draft';

    /** The organization keeps posted entries final. */
    case Strict = 'strict';

    case Archived = 'archived';
    case FiscalYearClosed = 'fiscal_year_closed';
    case VatLocked = 'vat_locked';

    /** Created by an invoice, expense, payroll, bank or asset workflow. */
    case SourceManaged = 'source_managed';

    /** Part of a guided correction or a reversal pair. */
    case CorrectionBound = 'correction_bound';

    /** Generated by the system: openings, settlements, closings. */
    case SystemGenerated = 'system_generated';

    /** At least one line is matched in a lettrage. */
    case Lettered = 'lettered';

    public function isAmendable(): bool
    {
        return $this === self::Open;
    }

    /** Whether the guided correction is the way out of this state. */
    public function suggestsCorrection(): bool
    {
        return in_array($this, [self::Strict, self::FiscalYearClosed, self::VatLocked], true);
    }

    public function label(): string
    {
        return __('app.journal_edit_state_'.$this->value);
    }
}
